"""Manual trigger for extraction: `python -m docfactory.agents.run_extraction "<bundle path>" [--entity <Entity> ...] [--force] [--no-notes] [--no-proposals]`.

The path is an ingested original, e.g. "ReadmeForge/references/ReadmeForge SRS v0.3.pdf". Every entity tagged in the file is extracted (or only the
named ones), one small LLM call per batch of its chunks; entities whose chunks did not change since the last run are skipped
unless --force. Settings come from .env like run_ingestion. Facts are saved as drafts, generated by okf-extraction-agent/<model>.
When all entities are extracted (no --entity), discovery then keeps the chunks that are in no fact as notes (the Note fact), unless --no-notes. Then it looks for kinds of knowledge the ontology has no entity for and stores them as pending type proposals
(`python -m docfactory.agents.apply_type_proposal --list`), unless --no-proposals. Finally the relationship graph of the scope is rebuilt (`<scope>/graph/relationships.md`).
"""
import argparse
import sys

from docfactory.agents.discoverer import Discoverer
from docfactory.agents.entity_extractor import EntityExtractor
from docfactory.agents.model_client_factory import default_client
from docfactory.agents.run_graph import write_graphs
from docfactory.agents.type_proposer import TypeProposer
from docfactory.bundle.source_store import SourceStore
from docfactory.env_file import load_env_file
from docfactory.extract.discovery_pipeline import discover_file
from docfactory.extract.extraction_pipeline import extract_file, format_reports
from docfactory.extract.proposal_pipeline import format_proposals, propose_types


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m docfactory.agents.run_extraction")
    parser.add_argument("path", help="an ingested original, as <scope>/references/<file name> (the path run_ingestion reports)")
    parser.add_argument("--entity", action="append", help="extract only this entity (repeatable), e.g. FunctionalRequirements")
    parser.add_argument("--force", action="store_true", help="re-extract entities whose chunks are unchanged")
    parser.add_argument("--no-notes", action="store_true", help="do not keep the chunks that are in no fact as notes")
    parser.add_argument("--no-proposals", action="store_true", help="do not look for new entity types in the chunks that are in no fact")
    args = parser.parse_args(argv)
    path = args.path.replace("\\", "/").strip("/")
    store = SourceStore()
    if store.read(path) is None:
        print(f"{path!r} is not an ingested original; ingested files:")
        for record in store.list():
            print(f"  {record.path}")
        return 1
    load_env_file()  # settings from .env; variables already set in the shell win
    try:
        client = default_client()
        reports = extract_file(path, EntityExtractor(client), args.entity, args.force)
        if not args.entity and not args.no_notes:
            reports.append(discover_file(path, Discoverer(client), args.force))
        proposals = propose_types(path, TypeProposer(client), args.force) if not args.entity and not args.no_proposals else None
    except ValueError as error:
        print(error)
        return 2
    print(format_reports(path, reports))
    if proposals is not None:
        print(format_proposals(proposals))
    print("\n".join(write_graphs([path.split("/")[0]])))  # the relationship graph of the scope, a derived view
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
