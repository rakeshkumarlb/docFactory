"""Manual trigger for extraction: `python -m docfactory.agents.run_extraction "<bundle path>" [--entity <Entity> ...] [--force]`.

The path is an ingested original, e.g. "ReadmeForge/references/ReadmeForge SRS v0.3.pdf". Every entity tagged in the file is extracted (or only the
named ones), one small LLM call per batch of its chunks; entities whose chunks did not change since the last run are skipped
unless --force. Settings come from .env like run_ingestion. Facts are saved as drafts, generated by okf-extraction-agent/<model>.
"""
import argparse
import sys

from docfactory.agents.entity_extractor import EntityExtractor
from docfactory.agents.model_client_factory import default_client
from docfactory.bundle.source_store import SourceStore
from docfactory.env_file import load_env_file
from docfactory.extract.extraction_pipeline import extract_file, format_reports


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m docfactory.agents.run_extraction")
    parser.add_argument("path", help="an ingested original, as <scope>/references/<file name> (the path run_ingestion reports)")
    parser.add_argument("--entity", action="append", help="extract only this entity (repeatable), e.g. FunctionalRequirements")
    parser.add_argument("--force", action="store_true", help="re-extract entities whose chunks are unchanged")
    args = parser.parse_args(argv)
    path = args.path.replace("\\", "/").strip("/")
    store = SourceStore()
    if store.read(path) is None:
        print(f"{path!r} is not an ingested original; ingested files:")
        for record in store.list():
            print(f"  {record.path}")
        return 1
    load_env_file()  # settings from .env; variables already set in the shell win
    try:
        reports = extract_file(path, EntityExtractor(default_client()), args.entity, args.force)
    except ValueError as error:
        print(error)
        return 2
    print(format_reports(path, reports))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
