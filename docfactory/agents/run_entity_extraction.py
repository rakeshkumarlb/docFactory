"""Manual trigger for entity-centric extraction: `python -m docfactory.agents.run_entity_extraction <scope> [--force]`.

For every recognized entity of the scope whose type is an item type (components, data stores, integrations, environments, alerts,
procedures, support contacts, known errors, ...), one small LLM call fills its item from every place that discusses it; unchanged entities
make no call unless --force. The touched facts are re-merged and saved; then recurring `proposed:<Name>` types of the graph are drafted as
pending type proposals (unless --no-proposals; apply one with `python -m docfactory.agents.apply_type_proposal <Name>`), and the scope's
relationship graph is rebuilt. Run it after
run_recognition (which builds the entity graph). Settings come from .env like run_ingestion; items are generated by
okf-entity-extraction-agent/<model>.
"""
import argparse
import sys

from docfactory.agents.entity_item_extractor import EntityItemExtractor
from docfactory.agents.model_client_factory import default_client
from docfactory.agents.run_graph import write_graphs
from docfactory.agents.type_proposer import TypeProposer
from docfactory.bundle.entity_store import EntityStore
from docfactory.env_file import load_env_file
from docfactory.extract.entity_item_pipeline import extract_entity_items
from docfactory.extract.extraction_pipeline import format_reports
from docfactory.extract.proposal_pipeline import format_proposals, propose_from_entities


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m docfactory.agents.run_entity_extraction")
    parser.add_argument("scope", help="a scope folder of the bundle, e.g. AI-Driven-Job-Matching-Platform or Shared")
    parser.add_argument("--force", action="store_true", help="fill every item again, even when its entity and evidence are unchanged")
    parser.add_argument("--no-proposals", action="store_true", help="do not draft type proposals for recurring proposed types")
    args = parser.parse_args(argv)
    if not EntityStore().list(args.scope):
        print(f"{args.scope!r} has no entity graph yet; run python -m docfactory.agents.run_recognition first")
        return 1
    load_env_file()  # settings from .env; variables already set in the shell win
    client = default_client()
    reports = extract_entity_items(args.scope, EntityItemExtractor(client), args.force)
    print(format_reports(f"{args.scope} (entities)", reports))
    if not args.no_proposals:
        for report in propose_from_entities(args.scope, TypeProposer(client), args.force):
            print(format_proposals(report))
    print("\n".join(write_graphs([args.scope])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
