"""Manual trigger for recognition: `python -m docfactory.agents.run_recognition ["<bundle path>" ...] [--scope <scope>] [--force]`.

Recognizes the entities and relationships of ingested originals, window by window (one small LLM call per changed window), stores each
file's recognition and rebuilds the scope's entity graph (`<scope>/entities/`). Without paths it recognizes every ingested original (of
`--scope` only, when given), oldest ingested first, so later documents see the entities of earlier ones. Unchanged windows make no call
unless --force. Then, per scope, entity resolution looks at each type's whole list for entities that are the same thing under different
names (one call per changed type, unless --no-resolve) and the graph is rebuilt with the decisions applied. Settings come from .env like run_ingestion; the recognition is generated by okf-recognition-agent/<model>.
"""
import argparse
import sys

from docfactory.agents.duplicate_resolver import DuplicateResolver
from docfactory.agents.entity_recognizer import EntityRecognizer
from docfactory.agents.model_client_factory import default_client
from docfactory.bundle.source_store import SourceStore
from docfactory.env_file import load_env_file
from docfactory.recognize.duplicate_resolution import resolve_scope
from docfactory.recognize.recognition_pipeline import format_report, rebuild_graph, recognize_file, scope_graph

SKIPPED_SCOPES = {"general"}  # originals that belong to no application give no entities


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m docfactory.agents.run_recognition")
    parser.add_argument("paths", nargs="*", help="ingested originals, as <scope>/references/<file name>; default: every ingested original")
    parser.add_argument("--scope", help="only the originals of this scope folder, e.g. AI-Driven-Job-Matching-Platform")
    parser.add_argument("--force", action="store_true", help="send every window to the model again, even when unchanged")
    parser.add_argument("--no-resolve", action="store_true", help="skip entity resolution (finding duplicates across documents)")
    args = parser.parse_args(argv)
    store = SourceStore()
    known = {r.path: r for r in store.list(args.scope)}
    paths = [p.replace("\\", "/").strip("/") for p in args.paths]
    unknown = [p for p in paths if store.read(p) is None]
    if unknown:
        print(f"not ingested originals: {unknown}; ingested files:")
        for record in store.list():
            print(f"  {record.path}")
        return 1
    if not paths:
        ordered = sorted(known.values(), key=lambda r: (r.timestamp, r.path))
        paths = [r.path for r in ordered if r.path.split("/")[0] not in SKIPPED_SCOPES]
    load_env_file()  # settings from .env; variables already set in the shell win
    client = default_client()
    recognizer = EntityRecognizer(client)
    for path in paths:
        print(format_report(recognize_file(path, recognizer, args.force)))
    if not args.no_resolve:
        resolver = DuplicateResolver(client)
        for scope in sorted({p.split("/")[0] for p in paths}):
            print("\n".join(resolve_scope(scope, scope_graph(scope, resolved=False)[0], resolver, args.force)))
            done, _ = rebuild_graph(scope)
            print(f"{scope}: entity graph rebuilt" + "".join(f", {len(ids)} {action}" for action, ids in done.items() if ids))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
